package compiler;

import compiler.codegen.BcProgram;
import compiler.codegen.CodeGenerator;
import compiler.codegen.VirtualMachine;
import compiler.codegen.VmException;
import compiler.ir.IrGenerator;
import compiler.ir.IrProgram;
import compiler.optimizer.Optimizer;
import compiler.parser.Ast;
import compiler.parser.AstPrinter;
import compiler.parser.Parser;
import compiler.scanner.MiniScanner;
import compiler.scanner.Token;
import compiler.semantic.SemanticAnalyzer;
import compiler.semantic.SemanticInfo;
import compiler.util.Diagnostic;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/** Command-line entry point of the MiniLang compiler. */
public final class Main {
    private static final String USAGE =
            "MiniLang compiler\n"
                    + "Usage: java -jar minic.jar [options] <file.mini>\n"
                    + "\n"
                    + "Stop-after options (show the output of one phase):\n"
                    + "  --tokens   Phase 1: print the token stream\n"
                    + "  --ast      Phase 2: print the abstract syntax tree\n"
                    + "  --ir       Phase 3: print the three-address IR (optimized when -O is given)\n"
                    + "  --asm      Phase 4: print the generated bytecode\n"
                    + "  --run      compile and execute (default when no stop-after option is given)\n"
                    + "\n"
                    + "Other options:\n"
                    + "  -O         Phase 5: enable the optimizer\n"
                    + "  --stats    print optimizer / VM statistics to stderr\n"
                    + "  --help     show this message\n"
                    + "\n"
                    + "Exit codes: 0 success, 1 compile error, 2 runtime error, 64 bad usage.\n";

    private Main() {}

    public static void main(String[] args) {
        System.exit(run(args));
    }

    static int run(String[] args) {
        boolean tokens = false, ast = false, ir = false, asm = false, optimize = false, stats = false;
        String file = null;
        for (String a : args) {
            switch (a) {
                case "--tokens": tokens = true; break;
                case "--ast": ast = true; break;
                case "--ir": ir = true; break;
                case "--asm": asm = true; break;
                case "--run": break;
                case "-O": optimize = true; break;
                case "--stats": stats = true; break;
                case "--help": case "-h": System.out.print(USAGE); return 0;
                default:
                    if (a.startsWith("-")) {
                        System.err.println("Unknown option: " + a + "\n");
                        System.err.print(USAGE);
                        return 64;
                    }
                    file = a;
            }
        }
        if (file == null) {
            System.err.print(USAGE);
            return 64;
        }

        String src;
        try {
            src = Files.readString(Path.of(file), StandardCharsets.UTF_8);
        } catch (IOException e) {
            System.err.println("Cannot read '" + file + "': " + e.getMessage());
            return 64;
        }

        // ---- Phase 1: scanner
        MiniScanner scanner = new MiniScanner(src);
        List<Token> toks = scanner.scanAll();
        if (tokens) {
            for (Token t : toks) System.out.println(t);
        }
        if (scanner.hadErrors()) return report(scanner.errors());
        if (tokens) return 0;

        // ---- Phase 2: parser
        Parser parser = new Parser(toks);
        Ast.Program program = parser.parseProgram();
        if (parser.hadErrors()) return report(parser.errors());
        if (ast) {
            System.out.print(AstPrinter.print(program));
            return 0;
        }

        // ---- Phase 3: semantic analysis + IR
        SemanticAnalyzer sema = new SemanticAnalyzer();
        SemanticInfo info = sema.analyze(program);
        if (sema.hadErrors()) return report(sema.errors());
        IrProgram irProgram = new IrGenerator(info).generate(program);

        // ---- Phase 5 (runs on the IR, before code generation)
        if (optimize) {
            Optimizer opt = new Optimizer();
            irProgram = opt.optimize(irProgram);
            if (stats) System.err.println(opt.stats());
        }
        if (ir) {
            System.out.print(irProgram);
            return 0;
        }

        // ---- Phase 4: code generation
        BcProgram bytecode = new CodeGenerator().generate(irProgram);
        if (asm) {
            System.out.print(bytecode);
            return 0;
        }

        // ---- execute
        VirtualMachine vm = new VirtualMachine(bytecode, System.out);
        try {
            vm.run();
        } catch (VmException e) {
            System.out.flush();
            System.err.println("Runtime error: " + e.getMessage());
            return 2;
        } finally {
            System.out.flush();
        }
        if (stats) System.err.println("VM instructions executed: " + vm.stepsExecuted());
        return 0;
    }

    private static int report(List<Diagnostic> errors) {
        for (Diagnostic d : errors) System.err.println(d);
        System.err.println(errors.size() + " error(s). Compilation failed.");
        return 1;
    }
}
